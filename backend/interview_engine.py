"""
interview_engine.py
====================
Adaptive, persona-driven interview engine.

PERSONA
-------
Senior tech interviewer. Dry. Sharp. Slightly sarcastic when a candidate
hand-waves. Deeply technical. Never moves on from a topic until the candidate
has demonstrated they actually understand it — or has clearly failed to.

DYNAMIC FLOW
------------
Every candidate answer is assessed for quality. The engine routes the next
turn based on that assessment, NOT on a rigid question sequence:

  GOOD answer   → advance to the next planned question.
  VAGUE / BRIEF → inject a sharp follow-up on the SAME topic before advancing.
  HANDWAVE      → inject a sarcastic, targeted counter before advancing.
  WEAK STREAK   → escalate tone; compress remaining plan.

A topic is drilled at most once (one follow-up max) so the interview doesn't
get stuck in an infinite loop. After a drill, the engine always moves forward.

MOCK MODE
---------
MOCK_MODE = True  → Each planned question also carries a simulated candidate
                    reply so you can drive the full flow from a test script
                    without typing. Replies are intentionally messy.

Set MOCK_MODE = False and implement _llm_reply() when wiring real AI.

TECHNICAL SPEC COMPLIANCE
--------------------------
- POST /api/interview maintained via main.py
- sessionId, 8+ questions / 4+ days enforced by question_generator.py
- Final FeedbackPayload (summary, strengths, gaps, next) produced by build_feedback()
"""

