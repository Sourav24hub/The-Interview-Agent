# ===========================================================================
# ANSWER QUALITY ASSESSMENT
# ===========================================================================

class AnswerQuality(str, Enum):
    GOOD      = "good"       # substantive, specific, technical
    VAGUE     = "vague"      # conceptually aware but no specifics
    BRIEF     = "brief"      # too short to assess
    HANDWAVE  = "handwave"   # buzzwords / tutorial references / non-answer


# Phrases that signal the candidate is parroting without real understanding
_HANDWAVE_PHRASES: list[str] = [
    "followed the tutorial",
    "just followed",
    "it just worked",
    "it worked",
    "pretty straightforward",
    "easy enough",
    "not really sure",
    "kind of",
    "sort of just",
    "basically just",
    "I think maybe",
    "I guess",
    "something like that",
    "I don't remember exactly",
    "more or less",
    "just ran the code",
    "copy pasted",
    "used the example",
    "took the sample",
]

# If the answer is shorter than this many words it's flagged BRIEF
_BRIEF_WORD_THRESHOLD = 35

# Vagueness patterns: mentions concepts but no concrete details
_VAGUE_PATTERNS: list[str] = [
    r"\b(vectors?|embeddings?|models?|agents?|pipelines?)\b.{0,60}$",  # topic noun, nothing after
    r"^[^.]{0,120}\.$",   # single short sentence
]


def assess_answer_quality(answer: str, question: InterviewQuestion) -> AnswerQuality:
    """
    Rule-based quality classifier.
    Returns HANDWAVE > BRIEF > VAGUE > GOOD in order of severity.
    """
    text  = answer.strip()
    lower = text.lower()
    words = text.split()

    # Check handwave phrases first (highest priority flag)
    if any(p in lower for p in _HANDWAVE_PHRASES):
        return AnswerQuality.HANDWAVE

    # Too short
    if len(words) < _BRIEF_WORD_THRESHOLD:
        return AnswerQuality.BRIEF

    # Vague: mentions the right domain words but no tool names or specific steps
    day_tools_lower = [t.lower() for t in (question.tools if hasattr(question, "tools") else [])]
    tool_mentioned  = any(t in lower for t in day_tools_lower) if day_tools_lower else True

    # Heuristic: if it's a DEPTH_VERIFY question and no tool name appears → vague
    if question.question_type == QuestionType.DEPTH_VERIFY and not tool_mentioned:
        return AnswerQuality.VAGUE

    # Count sentences as a proxy for elaboration
    sentence_count = len(re.split(r'[.!?]+', text))
    if sentence_count < 3:
        return AnswerQuality.VAGUE

    return AnswerQuality.GOOD


