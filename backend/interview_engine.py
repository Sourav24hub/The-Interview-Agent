def build_feedback(session_id: str) -> FeedbackPayload:
    session   = get_session(session_id)
    candidate = session["candidate"]
    plan      = session["question_plan"]

    missions_passed  = [m for m in candidate.missions if m.passed is True]
    missions_skipped = [m for m in candidate.missions if m.skipped]
    missions_failed  = [m for m in candidate.missions if m.passed is False]
    high_attempt     = [m for m in missions_passed if (m.attempts or 0) >= 4]

    total_turns = session["total_turns"]
    weak_count  = get_weak_turn_count(session_id)
    weak_ratio  = weak_count / total_turns if total_turns > 0 else 0

    depth_qs   = [q for q in plan if q.question_type == QuestionType.DEPTH_VERIFY]
    explore_qs = [q for q in plan if q.question_type == QuestionType.EXPLORE]

    strengths: list[str] = []
    gaps:      list[str] = []
    next_steps: list[str] = []

    # --- Strengths ---
    if candidate.signals.commitDays >= 25:
        strengths.append(
            f"Sustained engagement: {candidate.signals.commitDays} active days "
            f"demonstrates consistent work ethic throughout the 31-day cohort."
        )
    if candidate.signals.missionsFirstTry >= 15:
        strengths.append(
            f"High first-attempt accuracy: {candidate.signals.missionsFirstTry}/"
            f"{candidate.signals.missionsCompleted} missions passed first try — "
            f"indicates strong problem-solving approach and low rework rate."
        )
    elif candidate.signals.missionsFirstTry >= 8:
        strengths.append(
            f"Reasonable first-attempt rate ({candidate.signals.missionsFirstTry}/"
            f"{candidate.signals.missionsCompleted}) — shows deliberate preparation "
            f"before submitting solutions."
        )
    if len(missions_passed) >= 8:
        strengths.append(
            f"Broad coverage: {len(missions_passed)} missions completed across "
            f"multiple modules spanning data foundations to production deployment."
        )
    if weak_ratio < 0.25 and total_turns >= 5:
        strengths.append(
            f"Interview performance: answered with technical specificity across "
            f"{total_turns} turns — rarely required prompting for elaboration."
        )
    if not strengths:
        strengths.append(
            "Demonstrated persistence in completing the AI cohort despite significant "
            "difficulty across multiple mission areas."
        )

    # --- Gaps (informed by interview performance + mission history) ---
    if weak_ratio >= 0.5:
        gaps.append(
            f"Communication of technical depth: {weak_count}/{total_turns} interview turns "
            f"required follow-up prompting to elicit specific technical detail. "
            f"Candidate tends toward high-level answers without unprompted elaboration."
        )
    elif weak_ratio >= 0.25:
        gaps.append(
            f"Inconsistent depth in explanations: {weak_count} turns required drilling — "
            f"candidate is stronger on some topics than others."
        )
    if missions_skipped:
        titles = ", ".join(m.title for m in missions_skipped)
        gaps.append(
            f"Unverified areas from skipped missions: {titles}. "
            f"Gap exploration questions confirmed limited hands-on exposure."
        )
    if missions_failed:
        titles = ", ".join(m.title for m in missions_failed)
        gaps.append(
            f"Incomplete missions with outstanding knowledge gaps: {titles}. "
            f"Candidate acknowledged gaps when directly questioned."
        )
    if high_attempt:
        titles = ", ".join(m.title for m in high_attempt[:3])
        gaps.append(
            f"Persistent difficulty areas (4+ attempts): {titles}. "
            f"Struggle probe questions revealed underlying conceptual confusion "
            f"rather than simple implementation bugs."
        )
    if not gaps:
        gaps.append(
            "No critical gaps identified. Candidate demonstrated solid technical "
            "depth and honest self-assessment across all assessed areas."
        )

    # --- Next steps ---
    if weak_ratio >= 0.4:
        next_steps.append(
            "Practice articulating technical decisions out loud. The ability to explain "
            "not just what you did but WHY — and what could go wrong — is non-negotiable "
            "at the senior level."
        )
    if missions_skipped:
        next_steps.append(
            "Complete the skipped missions hands-on (not just read about them). "
            "Specifically: production deployment and security modules are "
            "table-stakes for any AI engineering role."
        )
    if missions_failed:
        next_steps.append(
            "Revisit failed missions by building a minimal standalone implementation "
            "from scratch — no starter code. Failure to pass under exam conditions "
            "usually means the mental model is wrong, not just the code."
        )
    if high_attempt:
        next_steps.append(
            "For topics that took 4+ attempts, build a side project that uses that "
            "concept as its core mechanism. Passive review will not fix a broken "
            "mental model."
        )
    next_steps.append(
        "Ship a production-grade AI project end-to-end: RAG retrieval, agent "
        "orchestration, deployment, and monitoring. Portfolio evidence matters "
        "more than cohort completion at the hiring stage."
    )
    next_steps.append(
        "Read the failure modes, not just the success paths. For every tool you "
        "used in this cohort, study: what makes it slow, what makes it fail silently, "
        "and what the production-safe alternative looks like."
    )

    # Summary
    q_days = len(set(q.day for q in plan))
    interview_quality = (
        "strong" if weak_ratio < 0.25
        else "mixed" if weak_ratio < 0.5
        else "below expectations"
    )
    summary = (
        f"{candidate.member.name} ({candidate.member.jobRole}, "
        f"{candidate.member.yearsExperience} yrs exp, {candidate.member.education}) "
        f"completed the AI cohort with {candidate.signals.missionsCompleted} missions, "
        f"{candidate.signals.commitDays} active days, and a "
        f"{candidate.signals.missionsFirstTry}/{candidate.signals.missionsCompleted} "
        f"first-try rate. "
        f"The interview covered {total_turns} turns across {q_days} curriculum days "
        f"with {weak_count} turns requiring follow-up probing. "
        f"Overall interview performance: {interview_quality}. "
        f"{'Recommend for next round with technical coding challenge.' if weak_ratio < 0.35 else 'Recommend a second technical screen before advancing.'}"
    )

    return FeedbackPayload(
        summary=summary,
        strengths=strengths,
        gaps=gaps,
        next=next_steps,
    )
