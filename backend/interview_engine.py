# SHARP FOLLOW-UP GENERATOR  (persona in action)
# ===========================================================================

# Each template receives keyword args: day_title, tool, objective, attempts
_FOLLOWUP_TEMPLATES: dict[AnswerQuality, list[str]] = {

    AnswerQuality.HANDWAVE: [
        (
            "Glad the {tool} tutorial exists. But tutorials are written for happy paths. "
            "Tell me what happens when {objective_challenge} — "
            "what breaks first, and how would you catch it before it hits production?"
        ),
        (
            "\"It worked\" is doing a lot of heavy lifting there. "
            "Walk me through specifically what *{tool}* is actually doing under the hood "
            "when you call it for this task. What would a wrong output look like, "
            "and how would you know?"
        ),
        (
            "Right. And if I put that code in front of a code reviewer who's never seen "
            "this cohort, what's the one thing they'd push back on immediately? "
            "Be specific about {day_title}."
        ),
        (
            "You said it \"just worked.\" In my experience, things that just work "
            "are things we don't fully understand yet. "
            "What's the most likely failure mode of your {day_title} implementation "
            "at 10x the data volume?"
        ),
    ],

    AnswerQuality.BRIEF: [
        (
            "That's a start. You've given me the \"what\" — I need the \"how\" and the \"why\". "
            "Walk me through the specific step in {day_title} where you hit resistance "
            "and what decision you made to get past it."
        ),
        (
            "Too short. You've described the outcome. I want to understand your reasoning. "
            "When you were working on {day_title}, what was the trade-off you had to make "
            "that wasn't spelled out in the objective? What did you sacrifice to get it done?"
        ),
        (
            "I appreciate the brevity but this isn't a stand-up. "
            "Tell me the one specific thing about {day_title} that you'd do "
            "differently if you were building it for a real enterprise system."
        ),
    ],

    AnswerQuality.VAGUE: [
        (
            "You've described the concept correctly — every candidate who read the docs can do that. "
            "I want to know what *you* specifically did with {tool} during {day_title}. "
            "What parameter, config, or architectural choice did you make that wasn't default?"
        ),
        (
            "That explanation would pass a multiple-choice quiz. "
            "Let's get concrete: when you ran {tool} on the actual mission data, "
            "what was the first output that surprised you, and what did it tell you "
            "about how the system actually behaves?"
        ),
        (
            "You clearly understand the theory. Here's the test: "
            "if your {day_title} implementation silently returned wrong results "
            "with no error — no exception, no crash — how would you detect it? "
            "What does your validation look like?"
        ),
    ],
}


def _generate_followup(
    quality: AnswerQuality,
    question: InterviewQuestion,
    weak_streak: int,
) -> str:
    """
    Pick and render a sharp follow-up for the given quality signal.
    Escalates sarcasm level if weak_streak > 1.
    """
    import random

    templates = _FOLLOWUP_TEMPLATES.get(quality, _FOLLOWUP_TEMPLATES[AnswerQuality.VAGUE])
    template  = random.choice(templates)

    tools     = getattr(question, "tools", [])
    tool_str  = tools[0] if tools else question.day_title
    objectives = getattr(question, "objectives", [])
    obj_challenge = objectives[-1] if objectives else f"the system fails mid-{question.day_title}"

    text = template.format(
        day_title=question.day_title,
        tool=tool_str,
        objective_challenge=obj_challenge,
    )

    # Escalate prefix for persistent weak streaks
    if weak_streak >= 2:
        prefix = (
            "I'm going to push on this again because the last two answers haven't "
            "convinced me you've actually built this. "
        )
        text = prefix + text

    return text


